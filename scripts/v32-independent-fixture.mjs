const root = process.cwd();
const directory = join(root, "fixtures/v3/v3.2-independent-validation-v1");
const checkOnly = process.argv.includes("--check");
const digest = (value) => createHash("sha256").update(value).digest("hex");
function tradingSessions(count) {
  const dates = [];
  const day = new Date("2024-01-01T00:00:00.000Z");
  while (dates.length < count) {
    const weekday = day.getUTCDay();
    if (weekday !== 0 && weekday !== 6) dates.push(day.toISOString().slice(0, 10));
    day.setUTCDate(day.getUTCDate() + 1);
  }
  return dates;
}

const sessions = tradingSessions(180);
const securities = ["000001.SZ", "600000.SH"];
const rows = ["security,date,availableAt,open,high,low,close,volume"];
for (const [securityIndex, security] of securities.entries()) {
  for (const [index, date] of sessions.entries()) {
    const trend = index < 60 ? index * 0.04 : index < 120 ? 2.4 - (index - 60) * 0.025 : 0.9 + (index - 120) * 0.055;
    const cycle = ((index * 7 + securityIndex * 11) % 13 - 6) * 0.035;
    const close = Number((10 + securityIndex * 17 + trend + cycle).toFixed(4));
    const open = Number((close + (((index + securityIndex) % 3) - 1) * 0.02).toFixed(4));
    const high = Number((Math.max(open, close) + 0.03).toFixed(4));
    const low = Number((Math.min(open, close) - 0.03).toFixed(4));
    const volume = 100_000 + ((index * 7919 + securityIndex * 104729) % 900_000);
    rows.push(`${security},${date},${date}T16:00:00+08:00,${open.toFixed(4)},${high.toFixed(4)},${low.toFixed(4)},${close.toFixed(4)},${volume}`);
  }
}
const bars = Buffer.from(`${rows.join("\n")}\n`, "utf8");

