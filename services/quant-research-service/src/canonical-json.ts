/** Canonical JSON for hashes over parsed JSON values. Object keys use the
 * locale-independent UTF-16 code-unit ordering used by ECMAScript string
 * comparison, so fingerprints do not depend on the host's default locale.
 */
export function canonicalJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.entries(value).sort(([left], [right]) => left < right ? -1 : left > right ? 1 : 0).map(([key, item]) => `${JSON.stringify(key)}:${canonicalJson(item)}`).join(",")}}`;
  }
  return JSON.stringify(value);
}
